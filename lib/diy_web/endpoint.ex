defmodule DIYWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :diy

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_diy_key",
    signing_salt: "ThkdxYog",
    same_site: "Lax"
  ]

  # Only the WebSocket, with a small frame: one VM serves all the users in
  # the 128 MB of a Durable Object, and the largest message is a build (see
  # DIYWeb.Device). The fallback of long polls is off: it reads a body of
  # 8 MB at most.
  socket "/live", Phoenix.LiveView.Socket,
    # peer_data: the address of the client, for the limit of the short
    # links (DIYWeb.Address).
    websocket: [
      connect_info: [:peer_data, session: @session_options],
      max_frame_size: 1_048_576
    ],
    longpoll: false

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :diy,
    gzip: not code_reloading?,
    only: DIYWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
  end

  plug Plug.RequestId
  # The log of a request has its path, except for the link of a shared
  # house: the path has the house (docs/design.md, "The link").
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint], log: {__MODULE__, :log_level, []}

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug DIYWeb.Router

  @doc "The level of the log of a request: none for the link of a shared house."
  def log_level(%Plug.Conn{path_info: ["s" | _]}), do: false
  def log_level(_conn), do: :info
end
